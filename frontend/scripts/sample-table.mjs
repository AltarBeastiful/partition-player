/**
 * Generates `src/voices.data.ts` (plan 0011, step 2): the sample map of every instrument the app
 * offers, read once from the sample collection's listing and committed as data.
 *
 * The app never lists a CDN at runtime — it fetches the files this table names, from the commit this
 * script pins. Run it by hand when an instrument is added:
 *
 *   node scripts/sample-table.mjs > src/voices.data.ts
 *
 * Thinning follows the collection's own `minify` rule: over 16 samples take every second, over 32
 * every fourth, so no set costs much more than the piano the app has always fetched.
 */
const REPO = "nbrosowsky/tonejs-instruments";
const PIN = "622c2f1c32c8cfce4158ddc3eb26e518ddef37e5"; // untouched since 2022-05-07
const CDN = `https://cdn.jsdelivr.net/gh/${REPO}@${PIN}/samples`;

/** The instruments offered, with the word the picker shows. */
const OFFERED = [
  ["flute", "Flute"],
  ["clarinet", "Clarinet"],
  ["saxophone", "Saxophone"],
  ["trumpet", "Trumpet"],
  ["french-horn", "French horn"],
  ["violin", "Violin"],
  ["cello", "Cello"],
  ["harp", "Harp"],
  ["guitar-nylon", "Nylon guitar"],
  ["organ", "Organ"],
  ["harmonium", "Harmonium"],
  ["xylophone", "Xylophone"],
];

const SEMITONE = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };

/** `Ds2.mp3` is D#2; the pitch number is what orders and ranges them. */
function noteOf(file) {
  const m = /^([A-G])(s?)(-?\d)\.mp3$/.exec(file);
  if (!m) return null;
  const [, step, sharp, octave] = m;
  const name = `${step}${sharp ? "#" : ""}${octave}`;
  return { name, midi: (Number(octave) + 1) * 12 + SEMITONE[step] + (sharp ? 1 : 0), file };
}

const CAP = 16;

/**
 * At most `CAP` samples a set, evenly spaced, the ends of the range always kept — the collection's
 * own `minify` rule generalized, so that a set of 38 files does not cost four times a set of 10.
 */
function thin(notes) {
  if (notes.length <= CAP) return notes;
  const every = Math.ceil(notes.length / CAP);
  const kept = notes.filter((_, i) => i % every === 0);
  const top = notes[notes.length - 1];
  if (kept[kept.length - 1] !== top) kept[kept.length - 1] = top;
  return kept;
}

async function listing(instrument) {
  const res = await fetch(`https://api.github.com/repos/${REPO}/contents/samples/${instrument}?ref=${PIN}`);
  if (!res.ok) throw new Error(`${instrument}: ${res.status} ${res.statusText}`);
  const notes = (await res.json())
    .map((entry) => entry.name)
    .map(noteOf)
    .filter(Boolean)
    .sort((a, b) => a.midi - b.midi);
  if (notes.length === 0) throw new Error(`${instrument}: no samples`);
  return notes;
}

const rows = [];
for (const [id, label] of OFFERED) {
  const all = await listing(id);
  const kept = thin(all);
  rows.push({
    id,
    label,
    baseUrl: `${CDN}/${id}/`,
    urls: Object.fromEntries(kept.map((n) => [n.name, n.file])),
    lowest: all[0].midi,
    highest: all[all.length - 1].midi,
    samples: `${kept.length} of ${all.length}`,
  });
}

const body = rows
  .map((r) => `  {
    id: ${JSON.stringify(r.id)},
    label: ${JSON.stringify(r.label)},
    baseUrl: ${JSON.stringify(r.baseUrl)},
    lowest: ${r.lowest},
    highest: ${r.highest},
    gain: 0,
    urls: ${JSON.stringify(r.urls)},
  }, // ${r.samples} samples`)
  .join("\n");

process.stdout.write(`/**
 * Generated by \`scripts/sample-table.mjs\` — do not edit by hand (plan 0011, step 2).
 *
 * The sample sets of github.com/${REPO}, pinned at ${PIN}
 * (a commit that has not moved since 2022-05-07). Samples CC-BY 3.0, code MIT; the credit is in the
 * page footer. \`lowest\` and \`highest\` are the written range of the set before thinning, so the
 * picker can say when a line goes under it and the sound will be a stretched sample.
 */
import type { SampleSet } from "./voices";

export const SETS: SampleSet[] = [
${body}
];
`);
